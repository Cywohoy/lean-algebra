"""Export complete mathematical code from the textbook, without Verso.

The ordinary library build does not need the textbook or this script.
Only savedLean blocks kept by the document are exported; exercise holes
are intentionally excluded. --check verifies the committed export.
"""
from pathlib import Path
import argparse
import re

BOOK = Path(__file__).resolve().parents[1]
# This branch owns the foundations modules only. Other Ample modules are untouched.
MODULES = [
    "Sets", "Functions", "Numbers", "Relations", "FiniteCardinality", "InfiniteCardinality",
]
ALIASES = {
    "Preliminaries": "import Ample.Math.Numbers\nimport Ample.Math.Relations\n",
    "Cardinality": "import Ample.Math.FiniteCardinality\nimport Ample.Math.InfiniteCardinality\n",
}

def library_import(module):
    if module.startswith("AlgebraBook.Tactic."):
        return module.replace("AlgebraBook.Tactic.", "Ample.Tactic.", 1)
    if module == "AlgebraBook.Meta.Notation":
        return "Ample.Notation"
    if module.startswith("AlgebraBook."):
        return module.replace("AlgebraBook.", "Ample.Math.", 1)
    return module

def without_textbook_annotations(body):
    """Keep Korean teaching notes in the book, outside the English library.

    Only standalone proof annotations (also after a tactic bullet) are omitted.
    Executable code, string literals, block comments, and license notices stay intact.
    """
    note = re.compile(r"^([ \t]*(?:·[ \t]*)?)--(?=[^\n]*[\uac00-\ud7a3])[^\n]*$")
    character = re.compile(r"'(?:\\.|[^'\\\n])'")
    raw_start = re.compile(r'r(#+)?"')
    result = []
    block_depth = 0
    string_end = ''
    raw = False
    for line in body.splitlines(keepends=True):
        # A comment-like line inside a multiline literal or block comment is
        # data, not a teaching annotation. Track these contexts lexically.
        if block_depth == 0 and not string_end:
            match = note.fullmatch(line.rstrip('\r\n'))
            if match and not re.search(r'copyright|license|spdx', match.group(), re.I):
                result.append(match[1].rstrip() + line[len(line.rstrip('\r\n')):])
                continue
        result.append(line)
        i = 0
        while i < len(line):
            if block_depth:
                if line.startswith('/-', i):
                    block_depth += 1
                    i += 2
                elif line.startswith('-/', i):
                    block_depth -= 1
                    i += 2
                else:
                    i += 1
            elif string_end:
                if not raw and line[i] == '\\':
                    i += 2
                elif line.startswith(string_end, i):
                    i += len(string_end)
                    string_end = ''
                else:
                    i += 1
            elif line.startswith('--', i):
                break
            elif line.startswith('/-', i):
                block_depth = 1
                i += 2
            elif match := character.match(line, i):
                i = match.end()
            elif match := raw_start.match(line, i):
                string_end = '"' + (match[1] or '')
                raw = True
                i = match.end()
            elif line[i] == '"':
                string_end = '"'
                raw = False
                i += 1
            else:
                i += 1
    return ''.join(result)

def export_module(source):
    chunks, imports = [], []
    for kind, flags, body in re.findall(r"^```(savedLean|savedImport|savedComment)([^\n]*)\n(.*?)^```\s*$", source, re.M | re.S):
        if kind == "savedImport":
            imports.extend(library_import(m) for m in re.findall(r"^import (\S+)", body, re.M))
        elif kind == "savedLean" and "-keep" not in flags.split():
            if re.search(r"\b(sorry|axiom)\b", re.sub(r"--[^\n]*", "", body)):
                raise ValueError("An admitted declaration cannot be exported to Ample.")
            # Legacy exercise aliases belong to the textbook, never the library.
            body = re.sub(r"^export_course_compat\s*$", "", body, flags=re.M)
            if body.strip():
                chunks.append(without_textbook_annotations(body).rstrip())
    header = "-- Generated by the textbook's scripts/sync_ample.py from complete savedLean blocks.\n"
    return header + "".join("import " + name + "\n" for name in dict.fromkeys(imports)) + "\n" + "\n\n".join(chunks) + "\n"

def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--book-root", type=Path, default=BOOK)
    parser.add_argument("--ample-root", type=Path,
                        help="Ample checkout (defaults to the sibling Ample directory).")
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    package = (args.ample_root or args.book_root.parent / "Ample").resolve()
    if not (package / "lakefile.toml").is_file():
        parser.error("Ample checkout not found. Supply its directory with --ample-root.")
    changed = []
    outputs = {package / "Ample/Math" / (name + ".lean"):
        export_module((args.book_root / "AlgebraBook" / (name + ".lean")).read_text(encoding="utf-8")) for name in MODULES}
    outputs.update({package / "Ample/Math" / (name + ".lean"): body for name, body in ALIASES.items()})
    for path, expected in outputs.items():
        if path.exists() and path.read_text(encoding="utf-8") == expected:
            continue
        changed.append(str(path.relative_to(package)))
        if not args.check:
            path.parent.mkdir(parents=True, exist_ok=True)
            path.write_text(expected, encoding="utf-8", newline="\n")
    if args.check and changed:
        raise SystemExit("Outdated mathematical exports:\n" + "\n".join(changed))
    print(f"Verified {len(outputs)} mathematical modules." if args.check else f"Exported {len(outputs)} mathematical modules ({len(changed)} changed).")

if __name__ == "__main__":
    main()
